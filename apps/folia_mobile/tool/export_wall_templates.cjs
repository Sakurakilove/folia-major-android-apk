const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const {execFileSync}=require('node:child_process');
const { baseline, sourceText, load } = require('./original_source.cjs');

// Export every original reflection and exact twelve-way expansion; no new wall layout is inferred.
const source = 'src/components/wall/blockTemplates.ts';
const reflows = 'src/components/wall/blockReflows.ts';
const model = load(source);
const templates = [], expansions = [];
const orientation = (column, row) => {
    let value = Math.imul(column, 0x9e3779b1) ^ Math.imul(row, 0x85ebca6b);
    value = Math.imul(value ^ (value >>> 15), 0x2c1b3c6d);
    value ^= value >>> 12;
    return (((column + row * 2) % 4 + 4) % 4) * 4 + (value >>> 0) % 4;
};
for (let row = -20; row <= 20; row++) for (let column = -20; column <= 20; column++) {
    const index = orientation(column, row);
    templates[index] = model.getBlockTemplate(column, row);
    expansions[index] = Array.from({ length: 12 }, (_, slot) => model.getBlockReflow(column, row, slot));
}
if (templates.filter(Boolean).length !== 16 || expansions.filter(Boolean).length !== 16) throw Error('Missing source wall reflection');
const slot = value => `WallBlockSlot(${value.x}, ${value.y}, ${value.cols}, ${value.rows})`;
const rows = values => values.map(value => `  [${value.map(slot).join(', ')}],`).join('\n');
const hashes = [source, reflows].map(file => `${file}: ${crypto.createHash('sha256').update(sourceText(file)).digest('hex')}`).join('\n// ');
const output = `// Generated by tool/export_wall_templates.cjs from mobile.17 ${baseline}.\n// ${hashes}\nimport 'wall_types.dart';\n\n// Reflection keeps source slot order and the complete exact block re-cover for each expansion.\nconst wallBlockTemplates = <List<WallBlockSlot>>[\n${rows(templates)}\n];\nconst wallBlockReflows = <List<List<WallBlockSlot>>>[\n${expansions.map(value => ` [\n${rows(value)}\n ],`).join('\n')}\n];\n`;
const target=path.join(__dirname, '../lib/library/wall/block_templates_data.dart');
fs.writeFileSync(target, output);
execFileSync(process.env.DART||'dart',['format',target],{stdio:'pipe'});
console.log('Exported 16 original wall orientations and 192 exact block reflows.');
