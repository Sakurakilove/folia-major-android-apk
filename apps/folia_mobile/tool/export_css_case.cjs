const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { baseline, sourceText } = require('./original_source.cjs');

// CSS uppercase for Folia's en/zh/id locales uses full default Unicode mapping; Dart's built-in simple mapping loses expansions.
const mappings = [];
for (let code = 0; code <= 0x10ffff; code++) {
    if (code >= 0xd800 && code <= 0xdfff) continue;
    const char = String.fromCodePoint(code), upper = char.toUpperCase();
    if (upper === char) continue;
    const escaped = Array.from({ length: upper.length }, (_, i) => `\\u${upper.charCodeAt(i).toString(16).padStart(4, '0')}`).join('');
    mappings.push(`  0x${code.toString(16)}: '${escaped}',`);
}
const output = `// Generated by tool/export_css_case.cjs; Unicode ${process.versions.unicode}, full default uppercase. Do not edit.\n// Unicode data license: assets/Unicode-LICENSE.txt.\nconst cssUppercaseMappings = <int, String>{\n${mappings.join('\n')}\n};\n`;
fs.writeFileSync(path.join(__dirname, '../lib/rendering/css_uppercase_data.dart'), output);
fs.writeFileSync(path.join(__dirname, '../assets/original/css_case_provenance.json'), JSON.stringify({ baseline,
    generator: 'tool/export_css_case.cjs', node: process.version, unicode: process.versions.unicode, v8: process.versions.v8,
    mappings: mappings.length, sha256: crypto.createHash('sha256').update(output).digest('hex'),
    source: ['src/components/visualizer/monet/VisualizerMonet.tsx', 'src/components/visualizer/VisualizerSubtitleOverlay.tsx'].map(file => ({ file,
        sha256: crypto.createHash('sha256').update(sourceText(file)).digest('hex') })),
    note: 'Default-case text transformation data, not browser text-transform/font/pixel acceptance. Locale-specific mod languages require their own CSS casing.' }, null, 2) + '\n');
console.log(`${mappings.length} full-uppercase scalar mappings exported from Unicode ${process.versions.unicode}.`);
