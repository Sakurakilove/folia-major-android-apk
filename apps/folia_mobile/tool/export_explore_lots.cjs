const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const { baseline, sourceText, load } = require('./original_source.cjs');

// Export all exact minimum-travel assignments once at build time; Android never repeats the original exponential focus-seat search.
const sources = ['src/components/app/lattice/lotTables.ts', 'src/components/app/lattice/lotSeats.ts'];
const { cutLot, cutGrownLot } = load(sources[1]);
const bytes = [], offsets = [];
const append = rect => {
    for (const n of [rect.x, rect.y, rect.cols, rect.rows]) {
        if (!Number.isInteger(n) || n < 0 || n > 255) throw Error('Lot byte overflow');
        bytes.push(n);
    }
};
for (let count = 0; count <= 13; count++) {
    offsets.push(bytes.length);
    for (let mirrors = 0; mirrors < 16; mirrors++) {
        const cut = cutLot(count, mirrors);
        append(cut.heading);
        cut.seats.forEach(append);
        for (let grown = 0; grown < count; grown++) cutGrownLot(count, mirrors, grown).forEach(append);
    }
}
const data = Buffer.from(bytes), encoded = data.toString('base64');
const hashes = sources.map(file => `// ${file}: ${crypto.createHash('sha256').update(sourceText(file)).digest('hex')}`).join('\n');
const target = path.join(__dirname, '../lib/library/wall/explore/explore_lot_data.dart');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, `// Generated by tool/export_explore_lots.cjs from mobile.17 ${baseline}.\n${hashes}\n// Packed bytes sha256: ${crypto.createHash('sha256').update(data).digest('hex')}\nimport 'dart:convert';\n\n// Lazily decoded only when an explore wall is used. Each count/mirror record contains heading, base seats, then every exact grown-seat assignment.\nfinal exploreLotBytes = base64Decode(\n${encoded.match(/.{1,120}/g).map(line => `  '${line}'`).join('\n')}\n);\nconst exploreLotOffsets = <int>[${offsets.join(', ')}];\n`);
execFileSync(process.env.DART || 'dart', ['format', target], { stdio: 'pipe' });
console.log(`Exported 224 original lots and 1456 exact grown-seat assignments (${bytes.length} bytes).`);
