const fs=require('node:fs'),path=require('node:path'),{execFileSync}=require('node:child_process');

// Numeric conversion facts from Chromium 154.0.8037.57 ui/gfx/color_conversions.cc and Skia 2466dcf3937437e217e7f284afe0e1aae15891ce SkColorSpace.h.
// Chromium goes through the ICC 16.16 XYZD50 matrix, not the textbook direct sRGB->Oklab matrix. These small differences survive CSS interpolation.
const f=Math.fround,mat=values=>values.map(row=>row.map(f));
const mul=(a,b)=>a.map(row=>b[0].map((_,c)=>f(f(f(row[0]*b[0][c])+f(row[1]*b[1][c]))+f(row[2]*b[2][c]))));
const vector=(a,v)=>a.map(row=>f(f(f(row[0]*v[0])+f(row[1]*v[1]))+f(row[2]*v[2])));
function inv(a){
 const cof=a.map((row,r)=>row.map((_,c)=>{
  const m=a.filter((_,i)=>i!==r).map(row=>row.filter((_,i)=>i!==c));
  return (r+c)%2?-m[0][0]*m[1][1]+m[0][1]*m[1][0]:m[0][0]*m[1][1]-m[0][1]*m[1][0];
 }));
 const det=a[0].reduce((s,n,c)=>s+n*cof[0][c],0);
 return a.map((row,r)=>row.map((_,c)=>f(cof[c][r]/det)));
}
const xyzToCone=mat([[.8951,.2664,-.1614],[-.7502,1.7135,.0367],[.0389,-.0685,1.0296]]),
 coneToXyz=mat([[.9869929,-.1470543,.1599627],[.4323053,.5183603,.0492912],[-.0085287,.0400428,.9684867]]),
 wx=f(.3127),wy=f(.329),src=vector(xyzToCone,[f(wx/wy),1,f(f(f(1-wx)-wy)/wy)]),dst=vector(xyzToCone,[f(.96422),1,f(.82521)]),
 adapt=mul(coneToXyz,mul(src.map((n,i)=>src.map((_,j)=>i===j?f(dst[i]/n):0)),xyzToCone)),
 gamut=[[0x6FA2,0x6299,0x24A0],[0x38F5,0xB785,0x0F84],[0x0390,0x18DA,0xB6CF]].map(row=>row.map(n=>n/65536)),
 xyzToLms=mat([[.8190224432164319,.3619062562801221,-.12887378261216414],[.0329836671980271,.9292868468965546,.03614466816999844],[.048177199566046255,.26423952494422764,.6335478258136937]]),
 labToLms=mat([[.9999999984505198,.39633779217376786,.2158037580607588],[1.0000000088817608,-.10556134232365635,-.0638541747717059],[1.000000054672411,-.08948418209496576,-1.2914855378640917]]),
 rgbToLms=mul(xyzToLms,mul(inv(adapt),gamut));
const constants={cssRgbToLms:rgbToLms,cssLmsToRgb:inv(rgbToLms),cssLabToLms:labToLms,cssLmsToLab:inv(labToLms)};
const target=path.join(__dirname,'../lib/rendering/css_color_matrices.dart');
fs.writeFileSync(target,'// Generated by tool/export_css_color_matrices.cjs; Chromium 154 / pinned Skia ICC XYZD50 conversion facts.\n'+Object.entries(constants).map(([key,rows])=>'const '+key+' = <List<double>>[\n'+rows.map(row=>'  ['+row.map(n=>Number.isInteger(n)?n+'.0':String(n)).join(', ')+'],').join('\n')+'\n];\n').join('\n'));
execFileSync(process.env.DART||'dart',['format',target],{stdio:'pipe'});
console.log('Exported Chromium ICC/D50 Oklab matrices.');
